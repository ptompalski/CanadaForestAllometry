#' Sharma (2016) DBH–height models for Ontario plantations and natural stands
#'
#' Vectorized implementation of the population-level individual-tree
#' height–diameter models of Sharma (2016), fitted separately to trees grown in
#' plantations and in natural stands in Ontario. Predicts total tree height (m)
#' from DBH (cm), stand origin and three stand-level predictors: dominant stand
#' height, basal area and stand density.
#'
#' \strong{Model scope (species coverage):} jack pine (`PINU.BAN`), red pine
#' (`PINU.RES`), black spruce (`PICE.MAR`) and white spruce (`PICE.GLA`), each
#' with a plantation and a natural-stand parameter set. Fitted to Ontario
#' permanent sample plots (400 m²); red pine plots are mostly in the southwest
#' of the province, the other species cover the boreal region (p. 71).
#'
#' \strong{Model form} (eq. 4, p. 75; same form as Sharma and Parton 2007, see
#' [hd_sharmaparton2007()]):
#' \deqn{H = 1.3 + \theta \, HDOM^{\delta}
#'   [1 - \exp(-\beta (TPH / BA)^{\phi} DBH)]^{\gamma}.}
#'
#' \strong{Height convention:} total tree height; DBH measured at 1.3 m, so
#' predicted height tends to 1.3 m as DBH tends to 0.
#'
#' \strong{Population-level prediction:} coefficients are the fixed effects of
#' the mixed-effects fit (Table 3, p. 74), evaluated with the plot-level random
#' effect on \eqn{\theta} set to zero (\eqn{u = 0}), as in Fig. 4 of the
#' source. Plot-specific calibration with measured heights is not implemented.
#'
#' \strong{Notes on the published coefficients:}
#' \itemize{
#'   \item As published, \eqn{\phi} is negative for red pine in natural stands,
#'     and \eqn{\delta} and \eqn{\phi} are negative for black spruce in natural
#'     stands (p. 75). For these, predicted height decreases slightly with
#'     `TPH / BA` (and, for natural black spruce, with `HDOM`).
#'   \item \eqn{\phi} for white spruce plantations is blank in Table 3 (the
#'     only non-significant parameter, p. 75). It is set to 0 here, so the
#'     `TPH / BA` term drops out and `BA` and `TPH` do not affect that model.
#'   \item Table 3 does not exactly reproduce the curves in Fig. 4 at large
#'     DBH (differences up to about 1.2 m at 40 cm); this function implements
#'     Table 3 as published.
#' }
#'
#' Rows with `NA` in any input return `NA` height. Inputs outside the range of
#' the fitting data for the species and stand origin (DBH, Table 2; BA, TPH and
#' HDOM, Table 1; p. 72) are computed and reported in a single warning.
#'
#' @param DBH Numeric vector. Tree level. Diameter at breast height (1.3 m
#'   above ground), in cm. Must be `>= 0`.
#' @param species Character vector. Tree level. NFI species codes (e.g.
#'   `"PICE.MAR"`; compact `"PICEMAR"` is accepted).
#' @param variant Character vector. Plot level. Stand origin selecting the
#'   parameter set: `"plantation"` (regenerated by planting) or `"natural"`
#'   (natural stand). No default; recycled like the other inputs, so stands of
#'   both origins can be predicted in one call. `NA` gives `NA` height.
#' @param HDOM Numeric vector. Plot level. Dominant stand height (m): "average
#'   height of dominant and codominant trees" in the plot (source "SHT",
#'   pp. 71-72). Must be `> 0`.
#' @param BA Numeric vector. Plot level. Total stand basal area (m²/ha) of the
#'   plot (source "BA", pp. 71-72). The source does not state a minimum DBH for
#'   this total. Must be `> 0`.
#' @param TPH Numeric vector. Plot level. Stand density (stems/ha),
#'   "calculated from the trees with dbh \eqn{\geq} 2.5 cm" (source "TPH",
#'   p. 71). Must be `> 0`.
#' @param keep_model_id Logical. If `TRUE`, add column `model_id`
#'   (`"sharma2016_natural"` or `"sharma2016_plantation"`).
#'
#' @return A tibble with column `height` (m) and, if `keep_model_id = TRUE`,
#'   `model_id`.
#'
#' @references
#' Sharma, M. (2016). Comparing height–diameter relationships of boreal tree
#' species grown in plantations and natural stands. Forest Science, 62(1),
#' 70–77. \doi{10.5849/forsci.14-232}
#'
#' @seealso [hd_sharmaparton2007()], [hd_model_registry()],
#'   [get_hd_model_info()]
#' @examples
#' hd_sharma2016(
#'   DBH = c(10, 20, 30),
#'   species = "PINU.RES",
#'   variant = c("plantation", "natural", "natural"),
#'   HDOM = 16, BA = 25, TPH = 2200
#' )
#'
#' # Inside dplyr::mutate() with tree and plot data
#' trees <- data.frame(
#'   DBH = c(12, 25, 18),
#'   species = c("PICE.MAR", "PICE.GLA", "PINU.BAN"),
#'   origin = c("plantation", "natural", "natural"),
#'   HDOM = c(12, 18, 18), BA = c(22, 30, 30), TPH = c(3000, 2000, 2000)
#' )
#' dplyr::mutate(trees, hd_sharma2016(DBH, species, origin, HDOM, BA, TPH))
#'
#' @export
hd_sharma2016 <- function(DBH, species, variant, HDOM, BA, TPH,
                          keep_model_id = FALSE) {
  fn <- "hd_sharma2016"

  rlang::check_required(variant)
  if (!is.logical(keep_model_id) || length(keep_model_id) != 1L || is.na(keep_model_id)) {
    cli::cli_abort("{.arg keep_model_id} must be TRUE or FALSE.")
  }
  assert_numeric_vec(DBH, "DBH", gte = 0, allow_na = TRUE)
  if (!is.character(species) && !is.factor(species)) {
    cli::cli_abort("{.arg species} must be a character vector.")
  }
  if (is.factor(variant)) variant <- as.character(variant)
  if (is.logical(variant) && all(is.na(variant))) variant <- as.character(variant)
  assert_choice(
    variant, "variant", c("natural", "plantation"),
    multiple = TRUE, allow_na = TRUE
  )
  assert_numeric_vec(HDOM, "HDOM", gt = 0, allow_na = TRUE)
  assert_numeric_vec(BA, "BA", gt = 0, allow_na = TRUE)
  assert_numeric_vec(TPH, "TPH", gt = 0, allow_na = TRUE)

  if (length(DBH) == 0L) {
    out <- tibble::tibble(height = numeric())
    if (keep_model_id) out$model_id <- character()
    return(out)
  }
  v <- assert_len_compat(
    DBH = DBH,
    species = as.character(species),
    variant = variant,
    HDOM = HDOM,
    BA = BA,
    TPH = TPH
  )

  p <- .sharma2016_prepare(v$species, v$variant)

  .hd_warn_out_of_range(
    list(DBH = v$DBH, BA = v$BA, TPH = v$TPH, HDOM = v$HDOM),
    lower = list(DBH = p$DBH_min, BA = p$BA_min, TPH = p$TPH_min, HDOM = p$HDOM_min),
    upper = list(DBH = p$DBH_max, BA = p$BA_max, TPH = p$TPH_max, HDOM = p$HDOM_max),
    fn = fn
  )

  height <- .hd_cr_stand(
    v$DBH, v$HDOM, v$BA, v$TPH,
    p$theta, p$delta, p$beta, p$phi, p$gamma
  )

  ok <- !is.na(height)
  if (any(ok & (!is.finite(height) | height <= 0))) {
    # nocov start
    # Defensive: theta, beta, gamma > 0 and positive predictors give finite
    # heights >= 1.3 m.
    cli::cli_abort("{.fn {fn}} produced non-finite or non-positive heights.")
    # nocov end
  }

  out <- tibble::tibble(height = height)
  if (keep_model_id) {
    out$model_id <- ifelse(is.na(p$Species), NA_character_, paste0("sharma2016_", p$variant))
  }
  out
}


# internal
# Returns one Table 3 parameter row per input row, matched on species and
# stand origin (`variant`); NA species or variant give an all-NA row.
.sharma2016_prepare <- function(species, variant, call = rlang::caller_env()) {
  pars <- .get_internal_data("parameters_hd_Sharma2016")
  assert_required_cols(
    pars,
    c(
      "Species", "variant", "theta", "delta", "beta", "phi", "gamma",
      "DBH_min", "DBH_max", "BA_min", "BA_max", "TPH_min", "TPH_max",
      "HDOM_min", "HDOM_max"
    ),
    object = "parameters_hd_Sharma2016"
  )
  pars <- as.data.frame(pars)

  sp <- standardize_species_code(trimws(species), keep_all = FALSE)
  bad <- unique(sp[!is.na(sp) & !sp %in% pars$Species])
  if (length(bad) > 0L) {
    cli::cli_abort(c(
      "Species not covered by the Sharma (2016) DBH\u2013height models: {.val {bad}}.",
      "i" = "Supported: {paste(sort(unique(pars$Species)), collapse = ', ')}."
    ), call = call)
  }

  key <- ifelse(is.na(sp) | is.na(variant), NA_character_, paste(sp, variant))
  out <- pars[match(key, paste(pars$Species, pars$variant)), , drop = FALSE]
  rownames(out) <- NULL
  out
}
